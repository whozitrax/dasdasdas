_RE = re.compile(r"(<tg-emoji\b[^>]*>.*?</tg-emoji>)|(" + "|".join(re.escape(k) for k in _keys) + r")\ufe0f?",
                 re.S)
MAX_ENTITIES = 90  # лимит Telegram — 100 сущностей на сообщение


def pe(name: str) -> str:
    """Ручная вставка: f'{pe("fire")} Горячо'"""
    ch, cid = CATALOG[name]
    return f'<tg-emoji emoji-id="{cid}">{ch}</tg-emoji>'


def decorate(html_text: str) -> str:
    """Заменяет обычные эмодзи из UI_MAP на премиум в HTML-тексте."""
    if not html_text or len(_RE.findall(html_text)) > MAX_ENTITIES:
        return html_text

    def repl(m: re.Match) -> str:
        if m.group(1):
            return m.group(1)
        return f'<tg-emoji emoji-id="{UI_MAP[m.group(2)]}">{m.group(0)}</tg-emoji>'

    return _RE.sub(repl, html_text)
